export type IconName = keyof typeof BOOTSTRAP_ICONS;

/**
 * Dessine une icône Bootstrap Icons dans le PDF, en vectoriel net (via svg2pdf.js).
 * Position (x, y) = coin haut-gauche du carré icône, taille en mm.
 */
export async function dessinerIconeSvg(
  doc: jsPDF,
  nom: IconName,
  x: number,
  y: number,
  tailleMm: number,
  couleur: string,
): Promise<void> {
  const def = BOOTSTRAP_ICONS[nom];
  if (!def) return;

  const svgMarkup =
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16">` +
    def.paths.map(p => `<path d="${p}" fill="${couleur}"/>`).join('') +
    `</svg>`;

  const svgEl = new DOMParser().parseFromString(svgMarkup, 'image/svg+xml').documentElement;
  await svg2pdf(svgEl as unknown as SVGElement, doc, { x, y, width: tailleMm, height: tailleMm });
}